'use strict';
// версия сборки: при публикации (tools/publish_pages.sh) сюда пишется метка, и все картинки грузятся с ?v=метка —
// браузер не смешивает старую картинку с новыми координатами спрайтов (было: «каша» вместо построек после обновления)
const BUILD_VER = '52762b9-1793111930';
function verUrl(u) { return BUILD_VER === 'dev' ? u : u + (u.includes('?') ? '&' : '?') + 'v=' + BUILD_VER; }
