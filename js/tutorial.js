function updateTutorial() {
  const el = document.getElementById('quest');
  if (S.tutorial.hidden) { if (el.innerHTML) el.innerHTML = ''; return; }
  let step = S.tutorial.step;
  while (step < TUTORIAL.length && TUTORIAL[step].ok()) {
    step++;
    S.tutorial.step = step;
    sfx('research');
    if (step < TUTORIAL.length) log('Задание выполнено!', 'good');
  }
  let h;
  if (step >= TUTORIAL.length) {
    h = `<h4>Обучение пройдено!</h4><div>Развивайте производство и исследования. Платите дань эльфам, пока не станете сильнее. Цель — «Ритуал свержения» и победа над Владыкой.</div><button data-act="hideTut" style="margin-top:4px">Скрыть</button>`;
  } else {
    h = `<h4>Задание ${step + 1}/${TUTORIAL.length}</h4><div>${TUTORIAL[step].t}</div><div class="dim" style="margin-top:3px;font-size:11px">H — справка · <span data-act="hideTut" style="cursor:pointer;text-decoration:underline">скрыть обучение</span></div>`;
  }
  if (el._h !== h) { el.innerHTML = h; el._h = h; }
}
ACT.hideTut = () => { S.tutorial.hidden = true; };
